        public static short[] For(ClientVersion v)
        {
            var t = (short[])Base.Clone();

            bool atLeast(int a, int b, int c, int d) => v >= new ClientVersion(a, b, c, d);

            if (atLeast(5, 0, 0, 0)) { t[0x0B] = 0x07; t[0x16] = -1; t[0x31] = -1; }
            else { t[0x0B] = 0x10A; t[0x16] = 0x01; t[0x31] = 0x01; }

            t[0xE1] = atLeast(5, 0, 9, 0) ? (short)-1 : (short)0x09;

            if (atLeast(6, 0, 1, 3)) { t[0xE3] = -1; t[0xE6] = 0x05; t[0xE7] = 0x0C; t[0xE8] = 0x0D; t[0xE9] = 0x4B; t[0xEA] = 0x03; }
            else { t[0xE3] = 0x4D; t[0xE6] = -1; t[0xE7] = -1; t[0xE8] = -1; t[0xE9] = -1; t[0xEA] = -1; }

            if (atLeast(6, 0, 1, 7)) { t[0x08] = 0x0F; t[0x25] = 0x15; }
            else { t[0x08] = 0x0E; t[0x25] = 0x14; }

            t[0xB9] = atLeast(6, 0, 14, 2) ? (short)0x05 : (short)0x03;

            if (atLeast(7, 0, 0, 0)) { t[0xEE] = 0x0A; t[0xEF] = 0x15; }
            else { t[0xEE] = -1; t[0xEF] = 0x15; }

            if (atLeast(7, 0, 9, 0)) { t[0x24] = 0x09; t[0x99] = 0x1E; t[0xBA] = 0x0A; t[0xF3] = 0x1A; t[0xF1] = 0x09; t[0xF2] = 0x19; }
            else { t[0x24] = 0x07; t[0x99] = 0x1A; t[0xBA] = 0x06; t[0xF3] = 0x18; t[0xF1] = -1; t[0xF2] = -1; }

            t[0x00] = atLeast(7, 0, 18, 0) ? (short)0x6A : (short)0x68;

            if (atLeast(7, 0, 64, 0)) { t[0xFA] = 0x01; t[0xFB] = 0x02; }
            if (atLeast(7, 0, 104, 0)) { t[0xD5] = 0x09; t[0xFD] = 2; }

            return t;
        }
